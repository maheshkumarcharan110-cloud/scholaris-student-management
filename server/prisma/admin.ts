import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import bcrypt from "bcryptjs";
import type { PrismaClient } from "@prisma/client";

const currentDir = path.dirname(fileURLToPath(import.meta.url));
const credentialsFile = path.resolve(currentDir, "../.admin-credentials");

export interface AdminConfig {
  name: string;
  email: string;
  password?: string;
}

export function getAdminConfig(): AdminConfig {
  const password = process.env.ADMIN_PASSWORD?.trim();
  return {
    name: process.env.ADMIN_NAME?.trim() || "Mahesh Kumar",
    email: (process.env.ADMIN_EMAIL?.trim() || "admin@scholaris.edu").toLowerCase(),
    password: password || undefined,
  };
}

function writeCredentialsFile(email: string, password: string, name: string) {
  const body = [
    "Scholaris initial administrator",
    "Generated by the secure bootstrap script. Keep this file private.",
    "",
    `Name:     ${name}`,
    `Email:    ${email}`,
    `Password: ${password}`,
    "",
    "Change this password from the Profile page after signing in.",
    "",
  ].join("\n");
  fs.writeFileSync(credentialsFile, body, { mode: 0o600 });
  try {
    fs.chmodSync(credentialsFile, 0o600);
  } catch {
    // Best effort on filesystems that do not support POSIX modes.
  }
}

/**
 * Creates or upgrades the single administrator account without duplicating users
 * and without resetting an existing password unless ADMIN_PASSWORD is provided.
 */
export async function ensureAdmin(prisma: PrismaClient) {
  const config = getAdminConfig();

  // Prefer the configured email. Otherwise upgrade the existing administrator.
  let admin =
    (await prisma.user.findUnique({ where: { email: config.email } })) ??
    (await prisma.user.findFirst({
      where: { role: { in: ["SUPER_ADMIN", "ADMIN"] } },
      orderBy: { createdAt: "asc" },
    }));

  let generatedPassword: string | undefined;
  let created = false;

  if (!admin) {
    generatedPassword = config.password ?? crypto.randomBytes(18).toString("base64url");
    admin = await prisma.user.create({
      data: {
        name: config.name,
        email: config.email,
        passwordHash: await bcrypt.hash(generatedPassword, 12),
        role: "SUPER_ADMIN",
      },
    });
    created = true;
    if (!config.password) writeCredentialsFile(config.email, generatedPassword, config.name);
  } else {
    const data: {
      name: string;
      role: "SUPER_ADMIN";
      active: boolean;
      email?: string;
      passwordHash?: string;
    } = {
      name: config.name,
      role: "SUPER_ADMIN",
      active: true,
    };

    if (admin.email !== config.email) {
      const conflict = await prisma.user.findUnique({ where: { email: config.email } });
      if (!conflict) data.email = config.email;
    }

    if (config.password) data.passwordHash = await bcrypt.hash(config.password, 12);

    admin = await prisma.user.update({ where: { id: admin.id }, data });
  }

  return {
    user: admin,
    created,
    passwordGenerated: Boolean(generatedPassword),
    credentialsFile: generatedPassword ? credentialsFile : null,
  };
}
